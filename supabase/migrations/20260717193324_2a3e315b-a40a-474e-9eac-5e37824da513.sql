CREATE OR REPLACE FUNCTION public.mirror_loss_draft_upload_to_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_claim uuid;
  v_tenant uuid;
  v_actor text;
  v_event_type text;
  v_file_added boolean;
  v_newly_signed boolean;
BEGIN
  v_file_added := NEW.file_path IS NOT NULL AND (TG_OP = 'INSERT' OR OLD.file_path IS DISTINCT FROM NEW.file_path);
  v_newly_signed := NEW.signature_status = 'signed' AND (TG_OP = 'INSERT' OR OLD.signature_status IS DISTINCT FROM NEW.signature_status);

  IF NOT v_file_added AND NOT v_newly_signed THEN
    RETURN NEW;
  END IF;

  SELECT ld.claim_id, ld.tenant_id
    INTO v_claim, v_tenant
  FROM public.loss_draft_tracking ld
  WHERE ld.id = NEW.loss_draft_id;

  IF v_claim IS NULL THEN
    RETURN NEW;
  END IF;

  v_event_type := CASE WHEN v_newly_signed THEN 'document_signed_all' ELSE 'document_uploaded' END;
  v_actor := CASE
    WHEN v_newly_signed THEN 'Signed document filed'
    WHEN NEW.is_template_generated THEN 'Document generated by ChecksOps'
    ELSE 'Document uploaded'
  END;

  IF NOT EXISTS (
    SELECT 1
    FROM public.homeowner_ledger_events hle
    WHERE hle.claim_id = v_claim
      AND hle.event_type = v_event_type
      AND hle.payload_json->>'loss_draft_document_id' = NEW.id::text
  ) THEN
    INSERT INTO public.homeowner_ledger_events (
      tenant_id, claim_id, event_type, occurred_at, actor_label, payload_json
    ) VALUES (
      v_tenant, v_claim, v_event_type,
      COALESCE(NEW.submitted_at, NEW.signed_at, now()),
      v_actor,
      jsonb_build_object(
        'loss_draft_document_id', NEW.id,
        'document_label', NEW.document_label,
        'document_type',  NEW.document_type,
        'document_name',  COALESCE(NEW.file_name, NEW.document_label),
        'file_name',      NEW.file_name,
        'note',           NEW.notes
      )
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_mirror_loss_draft_upload ON public.loss_draft_documents;
CREATE TRIGGER trg_mirror_loss_draft_upload
AFTER INSERT OR UPDATE OF file_path, signature_status, submitted_at ON public.loss_draft_documents
FOR EACH ROW EXECUTE FUNCTION public.mirror_loss_draft_upload_to_ledger();

CREATE OR REPLACE FUNCTION public.mirror_check_file_to_homeowner_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_claim uuid;
  v_tenant uuid;
  v_check_number text;
  v_event_type text;
  v_actor text;
BEGIN
  SELECT cii.claim_id, cii.tenant_id, cii.check_number
    INTO v_claim, v_tenant, v_check_number
  FROM public.check_intake_items cii
  WHERE cii.id = NEW.check_intake_item_id;

  IF v_claim IS NULL OR v_tenant IS NULL THEN
    RETURN NEW;
  END IF;

  v_event_type := CASE
    WHEN lower(COALESCE(NEW.source, '')) LIKE '%contractor%' THEN 'contractor_upload'
    ELSE 'document_uploaded'
  END;

  v_actor := CASE
    WHEN NEW.signature_request_id IS NOT NULL OR NEW.category IN ('signed_dtp', 'signed_document') THEN 'Signed document filed'
    WHEN NEW.source = 'mortgage_ops' THEN 'Mortgage Ops uploaded document'
    WHEN lower(COALESCE(NEW.source, '')) LIKE '%contractor%' THEN 'Contractor uploaded document'
    ELSE 'Document uploaded'
  END;

  IF NOT EXISTS (
    SELECT 1 FROM public.homeowner_ledger_events hle
    WHERE hle.payload_json->>'check_file_id' = NEW.id::text
      AND hle.event_type = v_event_type
  ) THEN
    INSERT INTO public.homeowner_ledger_events (
      tenant_id, claim_id, check_id, event_type, occurred_at, actor_label, payload_json, created_by
    ) VALUES (
      v_tenant, v_claim, NEW.check_intake_item_id, v_event_type, COALESCE(NEW.created_at, now()), v_actor,
      jsonb_build_object(
        'check_file_id', NEW.id,
        'document_name', NEW.file_name,
        'document_label', COALESCE(NULLIF(NEW.description, ''), NEW.file_name),
        'file_name', NEW.file_name,
        'category', NEW.category,
        'source', NEW.source,
        'check_number', v_check_number,
        'note', NEW.description
      ),
      NEW.uploaded_by
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_mirror_check_file_to_homeowner_ledger ON public.check_files;
CREATE TRIGGER trg_mirror_check_file_to_homeowner_ledger
AFTER INSERT ON public.check_files
FOR EACH ROW EXECUTE FUNCTION public.mirror_check_file_to_homeowner_ledger();

