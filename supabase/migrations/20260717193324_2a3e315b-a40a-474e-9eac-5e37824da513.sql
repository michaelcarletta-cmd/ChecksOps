CREATE OR REPLACE FUNCTION public.mirror_signature_request_to_homeowner_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_claim uuid;
  v_tenant uuid;
  v_check_id uuid;
BEGIN
  IF NEW.claim_id IS NOT NULL THEN
    SELECT c.id, c.tenant_id INTO v_claim, v_tenant
    FROM public.claims c
    WHERE c.id = NEW.claim_id;
  ELSIF NEW.check_intake_item_id IS NOT NULL THEN
    SELECT cii.claim_id, cii.tenant_id, cii.id INTO v_claim, v_tenant, v_check_id
    FROM public.check_intake_items cii
    WHERE cii.id = NEW.check_intake_item_id;
  END IF;

  IF v_claim IS NULL OR v_tenant IS NULL THEN
    RETURN NEW;
  END IF;

  IF v_check_id IS NULL THEN
    SELECT lt.check_intake_item_id INTO v_check_id
    FROM public.loss_draft_tracking lt
    WHERE lt.claim_id = v_claim
    ORDER BY lt.created_at DESC
    LIMIT 1;
  END IF;

  IF NEW.sent_at IS NOT NULL
     AND (TG_OP = 'INSERT' OR OLD.sent_at IS DISTINCT FROM NEW.sent_at OR OLD.status IS DISTINCT FROM NEW.status)
     AND NOT EXISTS (
       SELECT 1 FROM public.homeowner_ledger_events hle
       WHERE hle.claim_id = v_claim
         AND hle.event_type = 'document_sent'
         AND hle.payload_json->>'signature_request_id' = NEW.id::text
     ) THEN
    INSERT INTO public.homeowner_ledger_events (
      tenant_id, claim_id, check_id, event_type, occurred_at, actor_label, payload_json
    ) VALUES (
      v_tenant, v_claim, v_check_id, 'document_sent', NEW.sent_at, 'Document sent for signature',
      jsonb_build_object(
        'signature_request_id', NEW.id,
        'document_name', NEW.document_name,
        'document_label', NEW.document_name,
        'status', NEW.status
      )
    );
  END IF;

  IF (NEW.completed_at IS NOT NULL OR NEW.status = 'completed')
     AND (TG_OP = 'INSERT' OR OLD.completed_at IS DISTINCT FROM NEW.completed_at OR OLD.status IS DISTINCT FROM NEW.status)
     AND NOT EXISTS (
       SELECT 1 FROM public.homeowner_ledger_events hle
       WHERE hle.claim_id = v_claim
         AND hle.event_type = 'document_signed_all'
         AND hle.payload_json->>'signature_request_id' = NEW.id::text
     ) THEN
    INSERT INTO public.homeowner_ledger_events (
      tenant_id, claim_id, check_id, event_type, occurred_at, actor_label, payload_json
    ) VALUES (
      v_tenant, v_claim, v_check_id, 'document_signed_all', COALESCE(NEW.completed_at, now()), 'Document fully signed',
      jsonb_build_object(
        'signature_request_id', NEW.id,
        'document_name', NEW.document_name,
        'document_label', NEW.document_name,
        'status', NEW.status
      )
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_mirror_signature_request_to_homeowner_ledger ON public.signature_requests;
CREATE TRIGGER trg_mirror_signature_request_to_homeowner_ledger
AFTER INSERT OR UPDATE OF sent_at, status, completed_at ON public.signature_requests
FOR EACH ROW EXECUTE FUNCTION public.mirror_signature_request_to_homeowner_ledger();

CREATE OR REPLACE FUNCTION public.mirror_signature_signer_to_homeowner_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_req record;
  v_claim uuid;
  v_tenant uuid;
  v_check_id uuid;
BEGIN
  IF NEW.status <> 'signed' OR (TG_OP = 'UPDATE' AND OLD.status IS NOT DISTINCT FROM NEW.status) THEN
    RETURN NEW;
  END IF;

  SELECT sr.id, sr.claim_id, sr.check_intake_item_id, sr.document_name
    INTO v_req
  FROM public.signature_requests sr
  WHERE sr.id = NEW.signature_request_id;

  IF v_req.claim_id IS NOT NULL THEN
    SELECT c.id, c.tenant_id INTO v_claim, v_tenant
    FROM public.claims c
    WHERE c.id = v_req.claim_id;
  ELSIF v_req.check_intake_item_id IS NOT NULL THEN
    SELECT cii.claim_id, cii.tenant_id, cii.id INTO v_claim, v_tenant, v_check_id
    FROM public.check_intake_items cii
    WHERE cii.id = v_req.check_intake_item_id;
  END IF;

  IF v_claim IS NULL OR v_tenant IS NULL THEN
    RETURN NEW;
  END IF;

  IF v_check_id IS NULL THEN
    SELECT lt.check_intake_item_id INTO v_check_id
    FROM public.loss_draft_tracking lt
    WHERE lt.claim_id = v_claim
    ORDER BY lt.created_at DESC
    LIMIT 1;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.homeowner_ledger_events hle
    WHERE hle.claim_id = v_claim
      AND hle.event_type = 'endorsement_signed'
      AND hle.payload_json->>'signer_id' = NEW.id::text
  ) THEN
    INSERT INTO public.homeowner_ledger_events (
      tenant_id, claim_id, check_id, event_type, occurred_at, actor_label, payload_json
    ) VALUES (
      v_tenant, v_claim, v_check_id, 'endorsement_signed', COALESCE(NEW.signed_at, now()), NEW.signer_name,
      jsonb_build_object(
        'signature_request_id', NEW.signature_request_id,
        'signer_id', NEW.id,
        'signer_name', NEW.signer_name,
        'signer_email', NEW.signer_email,
        'document_name', v_req.document_name,
        'document_label', v_req.document_name
      )
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_mirror_signature_signer_to_homeowner_ledger ON public.signature_signers;
CREATE TRIGGER trg_mirror_signature_signer_to_homeowner_ledger
AFTER INSERT OR UPDATE OF status, signed_at ON public.signature_signers
FOR EACH ROW EXECUTE FUNCTION public.mirror_signature_signer_to_homeowner_ledger();