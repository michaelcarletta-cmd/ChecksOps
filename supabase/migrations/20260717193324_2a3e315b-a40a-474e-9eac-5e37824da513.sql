  ) VALUES (
    v_tenant, v_claim, NEW.check_id, 'ops_note', COALESCE(NEW.created_at, now()), COALESCE(v_actor, 'Team note'),
    jsonb_build_object(
      'check_message_id', NEW.id,
      'note', NEW.body,
      'check_number', v_check_number
    ),
