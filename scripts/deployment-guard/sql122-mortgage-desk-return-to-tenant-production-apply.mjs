#!/usr/bin/env node
/**
 * Official production entry for SQL 122 (aws/workflows/sql/122_mortgage_desk_return_to_tenant.sql):
 * the Mortgage Desk returns its work to the tenant. The column
 * mortgage_handling_requests.return_emailed_at and six SECURITY DEFINER functions: five with EXECUTE
 * for checksops (a Desk message and a Desk document on the request's check, the shipping / mail-to /
 * dates of the request, the homeowner timeline row of a completed request, the once-per-request
 * "work returned" email claim) and the internal working-request check for the owner only; see
 * ops/production-sql-122-apply.md.
 *
 *   --inspect                 read-only (BEGIN READ ONLY ... ROLLBACK): catalog state, the
 *                             fingerprint, prerequisites and preconditions; reads no table rows
 *   --apply --input <file>    receipt-gated apply (see lib/release-sql-production-cli.mjs and
 *                             ops/production-sql-122-apply.md)
 *
 * Credentials come only from the pinned production admin secret. Run only on a host with
 * private reachability into the production VPC; never from GitHub-hosted runners or Lambda.
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { repoRootFrom } from './lib/paths.mjs';
import { runReleaseProductionTool } from './lib/release-sql-production-cli.mjs';
import { enforceScriptGuard } from './require-guard.mjs';

export async function main(argv = process.argv.slice(2), env = process.env, deps = {}) {
  return runReleaseProductionTool(
    { key: 'sql122', scriptUrl: import.meta.url, enforceScriptGuard },
    argv,
    env,
    { root: repoRootFrom(import.meta.url), ...deps },
  );
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirect) {
  const code = await main();
  process.exitCode = typeof code === 'number' ? code : (code ? 0 : 1);
}
